<#
  Builds the generated parts of "Music Player for Mac" from the Windows skin,
  and packs the folder for copying to a Mac:

    Music Player for Mac\extension\skin.js      app\ui\player.js + player.css + the
                                                logo, wrapped the way MusicPlayer.exe
                                                wraps them
    Music Player for Mac\extension\icon.png     the app icon picture (from icon.png)
    Music Player for Mac\extension\icon128.png  the extension's own icon
    Music Player for Mac.zip                    the whole folder, ready to copy

  Run it after changing anything in app\ui:
      powershell -ExecutionPolicy Bypass -File tools\make-mac.ps1
#>
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
$ui   = Join-Path $here 'app\ui'
$mac  = Join-Path $here 'Music Player for Mac'
$ext  = Join-Path $mac 'extension'
$zip  = Join-Path $here 'Music Player for Mac.zip'
$utf8 = New-Object System.Text.UTF8Encoding($false)

foreach ($f in "$ui\player.js", "$ui\player.css", "$ui\icon.png", "$here\icon.png", "$ext\manifest.json") {
    if (-not (Test-Path $f)) { throw "Missing $f" }
}

# --- skin.js -------------------------------------------------------------------
$css  = [IO.File]::ReadAllText("$ui\player.css", $utf8)
$js   = [IO.File]::ReadAllText("$ui\player.js", $utf8)
$logo = 'data:image/png;base64,' + [Convert]::ToBase64String([IO.File]::ReadAllBytes("$ui\icon.png"))
$skin = "// Generated by tools\make-mac.ps1 from app\ui\player.js and player.css - edit those, not this.`n" +
        "(function(){`"use strict`";var __MP_CSS=" + ($css | ConvertTo-Json -Compress) +
        ";var __MP_ICON=" + ($logo | ConvertTo-Json -Compress) + ";`n" + $js + "`n})();`n"
[IO.File]::WriteAllText("$ext\skin.js", $skin, $utf8)
"skin.js      $([Math]::Round($skin.Length / 1KB)) KB"

# --- icons -----------------------------------------------------------------------
Copy-Item "$here\icon.png" "$ext\icon.png" -Force
Add-Type -AssemblyName System.Drawing
$src = [System.Drawing.Image]::FromFile("$here\icon.png")
try {
    $bmp = New-Object System.Drawing.Bitmap 128, 128
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
    $g.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::HighQuality
    $side = [Math]::Min($src.Width, $src.Height)
    $g.DrawImage($src, (New-Object System.Drawing.Rectangle 0, 0, 128, 128),
        (New-Object System.Drawing.Rectangle ([int](($src.Width - $side) / 2)), ([int](($src.Height - $side) / 2)), $side, $side),
        [System.Drawing.GraphicsUnit]::Pixel)
    $g.Dispose()
    $bmp.Save("$ext\icon128.png", [System.Drawing.Imaging.ImageFormat]::Png)
    $bmp.Dispose()
} finally { $src.Dispose() }
"icons        icon.png, icon128.png"

# --- the zip (entries with forward slashes, which the Mac expects) -----------------
Add-Type -AssemblyName System.IO.Compression, System.IO.Compression.FileSystem
if (Test-Path $zip) { Remove-Item $zip -Force }
$fs = [IO.File]::Open($zip, [IO.FileMode]::CreateNew)
$za = New-Object System.IO.Compression.ZipArchive($fs, [System.IO.Compression.ZipArchiveMode]::Create)
try {
    $root = Split-Path -Leaf $mac
    Get-ChildItem $mac -Recurse -File | ForEach-Object {
        $rel = $_.FullName.Substring($mac.Length + 1).Replace('\', '/')
        $entry = $za.CreateEntry("$root/$rel", [System.IO.Compression.CompressionLevel]::Optimal)
        $entry.LastWriteTime = $_.LastWriteTime
        $out = $entry.Open()
        try { $bytes = [IO.File]::ReadAllBytes($_.FullName); $out.Write($bytes, 0, $bytes.Length) } finally { $out.Dispose() }
    }
} finally { $za.Dispose(); $fs.Dispose() }
"zip          $zip ($([Math]::Round((Get-Item $zip).Length / 1KB)) KB)"
